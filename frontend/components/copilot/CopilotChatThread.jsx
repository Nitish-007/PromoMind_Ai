"use client";

import React, { useState, useRef, useEffect } from "react";
import { Send, Bot, User, RotateCcw, Sparkles, TrendingUp } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";

export function CopilotChatThread({
  messages,
  isLoading,
  onSendMessage,
  onClearHistory,
  onLoadPlanDirect,
  onLoadIdeaDirect,
}) {
  const [inputValue, setInputValue] = useState("");
  const messagesEndRef = useRef(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, isLoading]);

  const handleSubmit = (e) => {
    e?.preventDefault();
    if (!inputValue.trim() || isLoading) return;
    onSendMessage(inputValue.trim());
    setInputValue("");
  };

  return (
    <div className="flex flex-col h-[620px] rounded-2xl border border-border bg-card shadow-xs overflow-hidden">
      {/* Chat Card Top Bar */}
      <div className="flex items-center justify-between border-b border-border px-4 py-3 bg-card">
        <div className="flex items-center gap-2.5">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-foreground text-background">
            <Bot className="h-4 w-4" />
          </div>
          <div>
            <h4 className="text-sm font-semibold text-foreground">
              AI Retail Copilot &amp; Sales Growth Advisor
            </h4>
            <div className="flex items-center gap-1.5 text-xs text-muted-foreground">
              <span className="h-1.5 w-1.5 rounded-full bg-emerald-500 animate-pulse" />
              <span>Live Gemini Engine + Price Elasticity Active</span>
            </div>
          </div>
        </div>

        <Button
          variant="ghost"
          size="sm"
          onClick={onClearHistory}
          className="text-xs h-8 px-2.5 gap-1.5 text-muted-foreground hover:text-foreground"
          title="Clear Conversation"
        >
          <RotateCcw className="h-3.5 w-3.5" />
          <span>Clear</span>
        </Button>
      </div>

      {/* Message Thread Area */}
      <div className="flex-1 overflow-y-auto p-4 space-y-4">
        {messages.map((msg, idx) => (
          <div
            key={idx}
            className={`flex gap-3 ${msg.sender === "user" ? "justify-end" : "justify-start"}`}
          >
            {msg.sender === "bot" && (
              <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-muted border text-foreground mt-0.5">
                <Bot className="h-3.5 w-3.5 text-muted-foreground" />
              </div>
            )}

            <div className="max-w-[88%] space-y-2">
              <div
                className={`rounded-2xl px-4 py-3 text-sm leading-relaxed ${
                  msg.sender === "user"
                    ? "bg-foreground text-background font-medium rounded-tr-xs"
                    : "bg-muted/50 border border-border text-foreground rounded-tl-xs whitespace-pre-line"
                }`}
              >
                {msg.text}

                {/* Sales Growth Advisor 3-Pillar Breakdown Card (Issue #8) */}
                {msg.sales_growth_plan && (
                  <div className="mt-3 rounded-xl border border-border bg-card p-3.5 text-foreground space-y-2.5">
                    <div className="flex items-center justify-between border-b border-border pb-2">
                      <span className="text-xs font-bold uppercase tracking-wider flex items-center gap-1.5">
                        <TrendingUp className="h-3.5 w-3.5 text-emerald-500" />
                        Sales Growth Advisor Roadmap
                      </span>
                      <Badge variant="outline" className="text-[10px] font-semibold">
                        +₹{(msg.sales_growth_plan.projected_monthly_lift_inr || 34200).toLocaleString("en-IN")} Monthly Potential
                      </Badge>
                    </div>
                    <div className="grid grid-cols-1 gap-2">
                      {(msg.sales_growth_plan.pillars || []).map((pil, pIdx) => (
                        <div key={pIdx} className="p-2 rounded-lg bg-muted/40 border border-border/60 text-xs">
                          <div className="flex items-center justify-between font-semibold text-foreground">
                            <span>{pIdx + 1}. {pil.title}</span>
                            <span className="text-emerald-600 dark:text-emerald-400">{pil.impact}</span>
                          </div>
                          <p className="text-[11px] text-muted-foreground mt-0.5">{pil.action}</p>
                        </div>
                      ))}
                    </div>
                  </div>
                )}

                {/* Inline Offer Cards generated by AI */}
                {msg.plan && (
                  <div className="mt-3 rounded-xl border border-border bg-card p-3.5 text-foreground space-y-2.5">
                    <div className="flex items-center justify-between gap-2">
                      <Badge variant="outline" className="text-xs font-semibold uppercase tracking-wider">
                        Ready Bundle
                      </Badge>
                      <span className="text-xs font-semibold text-emerald-600 dark:text-emerald-400">
                        ✓ {msg.plan.net_margin_pct ?? 18}% Net Margin
                      </span>
                    </div>

                    <div className="text-sm font-bold text-foreground">
                      {msg.plan.title}
                    </div>

                    <div className="text-xs text-muted-foreground">
                      <strong>{msg.plan.anchor_product?.name || "Anchor SKU"}</strong> +{" "}
                      <strong>{msg.plan.attached_product?.name || "Attached SKU"}</strong>
                    </div>

                    <div className="flex items-baseline gap-2 pt-1">
                      <span className="text-base font-bold text-foreground">
                        ₹{Math.round(msg.plan.recommended_combo_price || msg.plan.combo_price || 0)}
                      </span>
                      <span className="text-xs line-through text-muted-foreground">
                        ₹{Math.round(msg.plan.original_combined_mrp || 0)}
                      </span>
                      <span className="text-xs font-medium text-emerald-600 dark:text-emerald-400">
                        Save ₹{Math.round(msg.plan.discount_amount || 0)} ({msg.plan.discount_pct}% OFF)
                      </span>
                    </div>

                    <Button
                      size="sm"
                      onClick={() => onLoadPlanDirect(msg.plan)}
                      className="w-full text-xs h-8 mt-1 gap-1.5 shadow-xs"
                    >
                      <Sparkles className="h-3.5 w-3.5" />
                      <span>View WhatsApp Broadcast, Poster &amp; Cashier Script</span>
                    </Button>
                  </div>
                )}

                {/* Inline Weekly Offer Ideas */}
                {msg.ideas && msg.ideas.length > 0 && (
                  <div className="mt-3 space-y-2">
                    {msg.ideas.map((idea, iIdx) => (
                      <div
                        key={iIdx}
                        className="rounded-xl border border-border bg-card p-3 text-foreground space-y-1.5"
                      >
                        <div className="flex items-center justify-between">
                          <span className="text-xs font-semibold uppercase text-muted-foreground">
                            {idea.badge || "RECOMMENDED"}
                          </span>
                          <span className="text-xs font-semibold text-emerald-600 dark:text-emerald-400">
                            {idea.net_margin_pct}% Margin
                          </span>
                        </div>
                        <div className="text-xs font-bold">{idea.title}</div>
                        <div className="text-[11px] text-muted-foreground">
                          {idea.anchor_name} + {idea.attached_name}
                        </div>
                        <div className="flex items-baseline gap-2">
                          <span className="text-sm font-bold">₹{Math.round(idea.combo_price)}</span>
                          <span className="text-[11px] line-through text-muted-foreground">
                            ₹{Math.round(idea.original_mrp)}
                          </span>
                          <span className="text-[11px] text-emerald-600 dark:text-emerald-400">
                            Save ₹{Math.round(idea.savings_amount)}
                          </span>
                        </div>
                        <p className="text-[11px] text-muted-foreground">
                          {idea.why_recommended}
                        </p>
                        {onLoadIdeaDirect && (
                          <Button
                            variant="outline"
                            size="sm"
                            onClick={() => onLoadIdeaDirect(idea)}
                            className="w-full text-xs h-7 mt-1"
                          >
                            Load Offer in Collateral Studio
                          </Button>
                        )}
                      </div>
                    ))}
                  </div>
                )}
              </div>

              <div className="flex items-center justify-between text-[10px] text-muted-foreground px-1">
                <span>{msg.time}</span>
                {msg.sender === "bot" && msg.generation_source && (
                  <span className="font-mono">{msg.generation_source}</span>
                )}
              </div>
            </div>

            {msg.sender === "user" && (
              <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-foreground text-background mt-0.5">
                <User className="h-3.5 w-3.5" />
              </div>
            )}
          </div>
        ))}

        {isLoading && (
          <div className="flex gap-3 justify-start">
            <div className="flex h-7 w-7 shrink-0 items-center justify-center rounded-full bg-muted border text-foreground mt-0.5">
              <Bot className="h-3.5 w-3.5 text-muted-foreground" />
            </div>
            <div className="rounded-2xl px-4 py-3 bg-muted/50 border border-border text-foreground text-sm flex items-center gap-2">
              <div className="h-4 w-4 animate-spin rounded-full border-2 border-foreground border-t-transparent" />
              <span>Generating live via Gemini AI &amp; computing price elasticity...</span>
            </div>
          </div>
        )}

        <div ref={messagesEndRef} />
      </div>

      {/* Input Bar */}
      <form onSubmit={handleSubmit} className="border-t border-border p-3 bg-card flex gap-2">
        <Input
          type="text"
          placeholder="Ask anything (e.g. 'Which product is failing?', 'Suggest 3 best offers', 'Festivals in Kerala')..."
          value={inputValue}
          onChange={(e) => setInputValue(e.target.value)}
          disabled={isLoading}
          className="text-sm h-10 bg-background"
        />
        <Button
          type="submit"
          size="sm"
          disabled={isLoading || !inputValue.trim()}
          className="h-10 px-4 text-sm font-medium gap-1.5 shrink-0"
        >
          <span>Send</span>
          <Send className="h-4 w-4" />
        </Button>
      </form>
    </div>
  );
}
